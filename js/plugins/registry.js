/**
 * Центральный реестр плагинов.
 * ============================================================
 *
 * Назначение файла
 * ----------------
 * Это ЕДИНСТВЕННОЕ место в приложении, где администратор/архитектор
 * проекта описывает:
 *   1. Какой набор плагинов доступен приложению (блок «Импорт плагинов»).
 *   2. К какому модулю (или модулям) подключается каждый плагин
 *      (блок «Карта привязок»).
 *
 * Почему это важно
 * ----------------
 * Раньше каждый плагин в своей собственной регистрации указывал
 *   `module: '3d-viewer'`
 * что нарушало разделение ответственности: плагин не должен знать,
 * в составе какого модуля он работает — это архитектурное решение,
 * которое принимает администратор. Аналогично, модули (3d-viewer.js,
 * 2d-viewer.js) раньше импортировали каждый плагин по отдельности,
 * что приводило к дублированию: при добавлении нового плагина
 * приходилось править и сам плагин, и модуль.
 *
 * Теперь:
 *   - Плагин (файл в /js/plugins/) только декларирует свою идентичность
 *     и поведение (id, name, icon, init, …) и НЕ знает своего модуля.
 *   - Модуль (3d-viewer.js / 2d-viewer.js / будущие) импортирует только
 *     этот реестр:  `import './plugins/registry.js';`
 *   - Администратор в этом файле решает, какой плагин к какому модулю
 *     относится. Поддерживается:
 *       '3d-viewer'                  — только 3D
 *       '2d-viewer'                  — только 2D
 *       ['3d-viewer', '2d-viewer']   — кросс-модульный плагин
 *       '*'                          — доступен во всех модулях
 *
 * Как добавить новый плагин
 * -------------------------
 *   1. Создать файл /js/plugins/my-plugin.js с вызовом PluginManager.register({...}).
 *   2. В этом файле:
 *        - добавить `import './my-plugin.js';`  в блок «Импорт плагинов»;
 *        - добавить запись в карту привязок:
 *            'my-plugin': ['3d-viewer', '2d-viewer'],   // или '*'
 *   3. Готово — модули подхватят плагин автоматически.
 *
 * Этот файл не имеет экспортов: его побочный эффект — регистрация
 * всех плагинов в PluginManager и установка привязок к модулям.
 */

